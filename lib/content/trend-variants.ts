const BY_VARIANT = new Map<TrendVariant, TrendVariantProfile>(TREND_VARIANTS.map((v) => [v.variant, v]));

export function isTrendVariant(v: unknown): v is TrendVariant {
  return typeof v === 'string' && BY_VARIANT.has(v as TrendVariant);
}

export function trendVariantProfile(variant: TrendVariant): TrendVariantProfile {
  return BY_VARIANT.get(variant)!;
}

